def build_all():
    if OUT.exists(): shutil.rmtree(OUT)
    CORE_DIR.mkdir(parents=True); SYS_DIR.mkdir(parents=True); GUIDE_DIR.mkdir(parents=True)
    builders=[build_core_concepts,build_terms,build_org,build_five_year,build_indicator,build_evidence,build_research,build_culture,build_education,build_operation]
    for (fname,_),fn in zip(CORE_FILES,builders): fn(CORE_DIR/(fname+'.docx'))
    for key,s in SYSTEMS.items():
        folder=SYS_DIR/key; folder.mkdir(parents=True)
        build_system_mother(folder,s)
        for i,item in enumerate(s['support'],2): build_support_doc(folder,s,i,item)
    build_guides(); build_index_readme()
    # subset archives and complete archive
    shutil.make_archive(str(OUT/'第一批十份核心文件_优化完善版_V2'),'zip',ROOT,'第一编_十份核心文件')
    shutil.make_archive(str(OUT/'第二批八系统及配套文件_优化完善版_V2'),'zip',ROOT,'第二编_八大系统建设文件')
    shutil.make_archive(str(OUT/'开江中学实验学校红专学校发展规划完整优化文件体系_V2'),'zip',OUT,ROOT.name)
    print('Generated docx:',len(list(ROOT.rglob('*.docx'))))
    for p in OUT.glob('*.zip'): print(p.name,p.stat().st_size)

if __name__=='__main__': build_all()
