def build_management(out: Path):
    title = f"{SCHOOL}集体备课规范化管理制度"
    doc = new_doc(title, "学情复盘·主备研讨·作业统筹·资源共享优化完善稿")
    add_callout(doc, "优化说明", "保留原制度每周集体备课和“四环节闭环”主体设计，重点把“统一”限定为课标进度、核心目标和质量底线的统一，允许教师根据班情进行二次设计；同时压减重复台账和全程检查。", LIGHT_GOLD)
    add_h1(doc, "一、指导思想")
    add_p(doc, "为落实减负提质、精准教学和高效课堂要求，充分发挥备课组的专业共同体作用，建立“上周学情复盘—下周主备说课—练习作业研讨—资源共享与二次设计—实施反馈”的集体备课闭环。集体备课既要形成学科年级共同质量标准，也要尊重教师专业创造和不同班级学生的实际差异。")
    add_h1(doc, "二、工作原则")
    add_bullets(doc, [
        "全员参与、责任到人：同年级同学科任课教师参加，主备教师提前准备，组员带着问题参会。",
        "学情为本、先诊后教：先解决上周遗留问题，再安排新授内容。",
        "共性统一、个性保留：统一课标进度、核心目标、重难点、质量底线和作业总量；课堂活动、教学路径和分层支持允许二次设计。",
        "问题导向、务求实效：一次备课集中解决3—5个关键问题，不追求议程和材料数量。",
        "资源共享、成果复用：形成可直接使用的教案框架、课件素材、作业与评价资源。",
        "减负留痕、抽样评价：每周一张记录表，已有资料不重复打印；管理部门以抽样观察和使用效果为主。",
    ])
    add_h1(doc, "三、组织、时间与基本要求")
    add_table(doc, ["项目", "要求"], [
        ["参与对象", "同年级同学科任课教师；教研组长、年级教学负责人按需参加"],
        ["频次", "原则上每周1次；小规模学科可隔周集中或跨年级联合"],
        ["时长", "常规60—90分钟；确需专题磨课可另行安排"],
        ["地点", "固定或线上共享空间均可，确保资料可展示、成员能充分研讨"],
        ["主备轮值", "备课组按单元或周次提前公布主备安排，原则上轮流承担"],
        ["会前准备", "主备教师提前2个工作日上传初稿；每名成员准备1个学情问题和1条修改建议"],
        ["材料上限", "每次只形成1张集体备课记录表和1个共享资源包，不另行制作重复汇报材料"],
    ], widths=[3.5, 12.5])
    add_h1(doc, "四、集体备课核心流程")
    add_h2(doc, "环节一：上周教学学情与考点掌握复盘")
    add_bullets(doc, [
        "梳理上周核心目标达成情况，区分已掌握、部分掌握和需要重新教学的内容。",
        "汇总课堂练习、作业、小测中的高频错题和典型思维障碍。",
        "分析不同班级和不同学习群体的差异，不给学生固定贴“优差”标签。",
        "确定补讲、补练、同伴互助、个别辅导和过关检查安排。",
    ])
    add_h2(doc, "环节二：下周教学内容主备教师说课")
    add_bullets(doc, [
        "说课标与教材：明确单元地位、内容结构和学业质量要求。",
        "说学情：依据已有课堂、作业和测评信息预判学习起点与困难。",
        "说目标：形成可观察、可评价的课时目标，兼顾知识、能力、素养与育人价值。",
        "说任务：说明核心学习任务、关键问题、学生活动和反馈方式。",
        "说重难点与课时：统一年级核心重难点和基本进度，明确允许调整的空间。",
    ])
    add_h2(doc, "环节三：练习、作业和阶段评价研讨")
    add_bullets(doc, [
        "选择与核心目标直接对应的课堂练习和课后作业，删除重复、偏难怪和低效机械题。",
        "统筹年级作业总量，设置基础必做、选择提升和个别支持三类任务。",
        "共同设计反馈方式，明确哪些问题当堂解决、哪些需要二次教学。",
        "小测和周练以诊断为主，控制频次和范围，不以统一测试替代日常教学。",
    ])
    add_h2(doc, "环节四：集体定案、资源共享与任务分工")
    add_bullets(doc, [
        "形成共同教案框架、核心资源、作业清单和评价要点。",
        "每位教师根据班情完成二次设计，并在共享资源中标注必要调整。",
        "明确下周磨课、听课、命题、资源整理、学困支持等任务及完成时间。",
        "确定下一次备课需要反馈的实施问题，完成闭环。",
    ])
    add_h1(doc, "五、不同教学阶段的备课重点")
    add_table(doc, ["类型", "重点问题", "主要成果"], [
        ["新授课", "概念形成、任务设计、学生参与、即时反馈", "课时目标、核心任务、关键问题、分层作业"],
        ["复习课", "知识结构、薄弱点、典型错因、迁移应用", "复习图谱、问题清单、分层训练和过关标准"],
        ["试卷讲评", "错误分类、原因诊断、二次变式、学习方法", "错因分析、精选讲评题、补救任务"],
        ["实验与实践课", "操作流程、器材安全、学生分工、成果评价", "安全清单、操作任务、观察记录和评价标准"],
        ["毕业年级", "进度统筹、基础保底、分层支持、心理节奏", "阶段计划、重点群体支持、作业与测评协调"],
    ], widths=[3.0, 7.0, 6.0])
    add_h1(doc, "六、岗位职责")
    add_table(doc, ["主体", "主要职责"], [
        ["备课组长", "制定轮值表；聚焦议题；控制时间；形成共同结论；协调跨班作业总量；跟踪实施问题"],
        ["主备教师", "提前独立精备；提供可讨论初稿；说明设计依据；吸收意见后整理共享资源"],
        ["组员教师", "提交学情问题；提出具体修改；完成二次设计；反馈实施效果和学生反应"],
        ["教研组长", "把握课程标准和学科质量；支持跨年级衔接；组织重点课题攻关"],
        ["教务处／教科室", "提供时间、资源和专业支持；进行抽样观察；解决跨组共性问题；不以签字数量评价质量"],
    ], widths=[4.0, 12.0])
    add_h1(doc, "七、成果与资料管理")
    add_bullets(doc, [
        "每周保存一份集体备课记录表和一个共享资源包，资源包可包含教案框架、课件、作业、评价工具等。",
        "电子资源统一命名为“年级—学科—单元／周次—日期”，设置组内编辑权限。",
        "不要求每位教师重复打印主备稿、说课稿、课件和记录表。",
        "个别学生信息、成绩明细和特殊支持记录不得上传至开放共享空间。",
        "成熟资源学期末整理进入学科资源库，低质量和重复资源及时清理。",
    ])
    add_h1(doc, "八、质量评价与改进")
    add_table(doc, ["评价领域", "观察要点", "证据"], [
        ["问题解决", "是否解决真实学情、作业和课堂问题", "后续课堂和作业变化、教师反馈"],
        ["专业参与", "成员是否有准备、有发言、有共同决策", "记录表、抽样旁听"],
        ["资源使用", "共同资源是否被使用并允许二次改进", "共享资源、二次设计样例"],
        ["学生受益", "学生理解、参与、作业负担和学习增值是否改善", "学生作品、作业样本、学情数据、抽样访谈"],
        ["教师负担", "会议时长、材料数量和重复劳动是否合理", "教师反馈、材料清单"],
    ], widths=[3.2, 6.4, 6.4])
    add_bullets(doc, [
        "教务处每月抽样参与少量备课组，不开展全覆盖周周检查。",
        "学期末各备课组只形成一页复盘：有效做法、主要困难、需要学校支持、下学期调整。",
        "对长期形式化、问题不聚焦的备课组，先提供专业指导和流程调整，不简单以扣分代替改进。",
    ])
    add_h1(doc, "九、附则")
    add_p(doc, "本制度经学校审议后试行，由教务处、教科室负责组织实施。各学科可在不降低核心要求的前提下形成符合学科特点的操作细则，试行一学期后根据教师和学生反馈修订。")
    add_signature_block(doc)
    save_doc(doc, out, "10_开江中学实验学校集体备课规范化管理制度（优化完善稿）.docx")


